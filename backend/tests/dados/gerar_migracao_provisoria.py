def gerar() -> str:
    registrar_modelos()
    eng = create_engine("sqlite://")
    with eng.connect() as conn:
        ctx = MigrationContext.configure(conn, opts={"compare_type": True})
        ops = api.produce_migrations(ctx, Base.metadata)
        up = render_python_code(ops.upgrade_ops, render_as_batch=False)
        down = render_python_code(ops.downgrade_ops, render_as_batch=False)
    # o render já indenta as operações; só os comentários de abertura/fechamento vêm na coluna 0
    ajustar = lambda txt: "\n".join(("    " + ln) if ln.startswith("# ###") else ln for ln in txt.splitlines())  # noqa: E731
    up, down = ajustar(up), ajustar(down)
    # o autogenerate não reflete índices por expressão: este é criado/removido à mão
    indice = (
        "    op.create_index(\n"
        "        'uq_aula_sessao_slot', 'aula_sessao',\n"
        "        ['unidade_id', 'tipo_servico_id', sa.text('coalesce(profissional_id, 0)'), 'data', 'hora_inicio'],\n"
        "        unique=True,\n"
        "    )\n"
    )
    up = up.replace("    # ### end Alembic commands ###", indice + "    # ### end Alembic commands ###")
    marca = "    # ### commands auto generated by Alembic - please adjust! ###\n"
    down = down.replace(marca, marca + "    op.drop_index('uq_aula_sessao_slot', table_name='aula_sessao')\n", 1)
    # O SQLite renderiza booleano como número (`DEFAULT 1`), que o PostgreSQL recusa: use sempre true()/false().
    def _booleanos(txt: str) -> str:
        txt = txt.replace("sa.Boolean(), server_default=sa.text('1')", "sa.Boolean(), server_default=sa.true()")
        return txt.replace("sa.Boolean(), server_default=sa.text('0')", "sa.Boolean(), server_default=sa.false()")

    up, down = _booleanos(up), _booleanos(down)
    return CABECALHO + up + "\n\n\ndef downgrade() -> None:\n" + down + "\n"


if __name__ == "__main__":
    DESTINO.parent.mkdir(parents=True, exist_ok=True)
    DESTINO.write_text(gerar(), encoding="utf-8")
    print("Migração gravada em", DESTINO)
